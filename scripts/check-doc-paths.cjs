// Guard against documentation drift: verify that file-path references in the
// repo's Markdown docs point at files that actually exist. Catches the most
// common drift class — a doc naming a source file that was later renamed,
// moved, or deleted (e.g. `script.js` after it became
// `src/components/script.ts`). Run via `npm run docs:check`; wired into CI
// (.github/workflows/ci.yml) and the pre-push gate (.claude/settings.json).
//
// It checks two kinds of references in each tracked *.md file:
//   1. Inline-code spans:      `src/lib/sync.ts`, `metrics.js`
//   2. Markdown link targets:  [text](smoke-index.spec.ts)
// A reference counts as a path only if it ends in a known file extension and
// contains no glob/whitespace/URL characters. Inline-code paths resolve from
// the repo root; link targets resolve from the doc's own directory. Trailing
// `:line` / `:line:col` suffixes are stripped before the existence check.
//
// Three escape hatches for references that are intentionally not real files
// (aspirational/future paths, gitignored local-only files, historical
// mentions): the ALLOWLIST below, an inline `<!-- doc-paths:ignore-line -->`
// marker on the same line, and the EXCLUDE_PREFIXES dir/file skip-list.
//
// Exit 0 if every reference resolves; exit 1 with a report otherwise. The
// check itself catches stale PATHS only; selectors, labels, status prose, and
// counts still need human/CodeRabbit review (see .coderabbit.yaml).

const fs = require("node:fs");
const path = require("node:path");
const { execSync } = require("node:child_process");

const repoRoot = path.resolve(__dirname, "..");

// Docs (or whole dirs) excluded from the check. These are frozen, point-in-time
// design/plan docs that intentionally cite files by their pre-migration names:
//  - plans/ holds implementation plans plus a "rejected findings" log that cite
//    now-deleted files by old names and line numbers; regenerated by the improve
//    skill, not a living description of current code.
//  - SUPABASE_PLAN.md is the pre-implementation backend design plan (single
//    commit, never updated); its `.js` references describe planned locations.
const EXCLUDE_PREFIXES = ["plans/", "SUPABASE_PLAN.md"];

// Exact reference strings that are intentionally not real repo files:
//  - aspirational/future paths a doc proposes creating
//  - gitignored local-only files (absent in a clean CI checkout)
//  - illustrative placeholders (hashed bundle names, etc.)
//  - source files that live inside a node_modules plugin, not this repo
const ALLOWLIST = new Set([
  "team.xcconfig", // gitignored, created locally (CLAUDE.md)
  "scripts/capture-screenshots-device.sh", // proposed fallback (store/screenshots/README.md)
  "legacy-globals-HASH.js", // illustrative hashed-bundle example (SENTRY_SETUP.md)
  "SplashScreen.swift", // @capacitor/splash-screen plugin source (SPLASH_HANDOFF.md)
  "SplashScreen.java", // @capacitor/splash-screen plugin source (SPLASH_HANDOFF.md)
  "ios/ExportOptions.plist", // gitignored per-developer signing config (store/UPLOAD.md)
]);

const IGNORE_LINE_MARKER = "<!-- doc-paths:ignore-line -->";

// File extensions that mark a token as a path worth resolving.
const EXT = [
  "js",
  "mjs",
  "cjs",
  "ts",
  "mts",
  "cts",
  "tsx",
  "jsx",
  "html",
  "css",
  "scss",
  "json",
  "jsonc",
  "sql",
  "sh",
  "swift",
  "java",
  "kt",
  "gradle",
  "kts",
  "xcconfig",
  "toml",
  "yml",
  "yaml",
  "plist",
  "md",
  "svg",
].join("|");
const PATH_LIKE = new RegExp("^[\\w./@-]+\\.(" + EXT + ")$");

// Existence is judged against git-tracked files (not the working tree), so the
// check behaves identically locally and in a clean CI checkout; intentionally
// untracked references (gitignored local files) belong in ALLOWLIST. A doc may
// also cite a file by basename alone (a sibling spec, or a migration without its
// supabase/migrations/ prefix); a basename that exists nowhere in the tree still
// fails, which is exactly the deleted/renamed-file drift we want caught.
const trackedFiles = execSync("git ls-files", { cwd: repoRoot, encoding: "utf8" })
  .split("\n")
  .map((s) => s.trim())
  .filter(Boolean);
const trackedPaths = new Set(trackedFiles);
const trackedBasenames = new Set(trackedFiles.map((f) => path.basename(f)));

function stripLineSuffix(token) {
  return token.replace(/:\d+(:\d+)?$/, "");
}

// A token whose first segment contains a dot is a host, not a path
// (e.g. cafelytic.com/login.html, js.sentry-cdn.com/x.min.js).
function looksLikeUrl(token) {
  const slash = token.indexOf("/");
  return slash > 0 && token.slice(0, slash).includes(".");
}

// Collect candidate references from a single line.
// kind "code" is a backtick span (resolved from repo root or the doc's dir);
// kind "link" is a markdown link target (resolved from the doc's dir).
function refsFromLine(line) {
  const out = [];
  for (const m of line.matchAll(/`([^`]+)`/g)) {
    out.push({ raw: m[1], kind: "code" });
  }
  for (const m of line.matchAll(/\]\(([^)]+)\)/g)) {
    out.push({ raw: m[1], kind: "link" });
  }
  return out;
}

function resolveTarget(ref, docDir) {
  let t = stripLineSuffix(ref.raw.split("#")[0].trim());
  if (!t || looksLikeUrl(t)) return null;
  // A leading slash in a runbook means the site root (e.g. `/login.html`),
  // which maps to the repo root for these page files.
  const rel = ref.kind === "code" && t.startsWith("/") ? t.slice(1) : t;
  if (!PATH_LIKE.test(rel)) return null;
  if (ALLOWLIST.has(t) || ALLOWLIST.has(rel)) return null;
  const bases = ref.kind === "link" ? [docDir] : [repoRoot, docDir];
  return { token: t, rel, abs: bases.map((b) => path.resolve(b, rel)) };
}

function listDocs() {
  const tracked = execSync("git ls-files '*.md'", { cwd: repoRoot, encoding: "utf8" })
    .split("\n")
    .map((s) => s.trim())
    .filter(Boolean);
  return tracked.filter((f) => !EXCLUDE_PREFIXES.some((p) => f.startsWith(p)));
}

const docs = listDocs();
const misses = [];
let refCount = 0;

for (const doc of docs) {
  const abs = path.join(repoRoot, doc);
  const docDir = path.dirname(abs);
  const lines = fs.readFileSync(abs, "utf8").split("\n");
  lines.forEach((line, i) => {
    if (line.includes(IGNORE_LINE_MARKER)) return;
    for (const ref of refsFromLine(line)) {
      const resolved = resolveTarget(ref, docDir);
      if (!resolved) continue;
      refCount += 1;
      const found =
        resolved.abs.some((a) => trackedPaths.has(path.relative(repoRoot, a))) ||
        (!resolved.rel.includes("/") && trackedBasenames.has(resolved.rel));
      if (!found) {
        misses.push({
          doc,
          line: i + 1,
          token: resolved.token,
          rel: path.relative(repoRoot, resolved.abs[0]),
        });
      }
    }
  });
}

if (misses.length === 0) {
  console.log(
    `docs:check PASS — ${refCount} file-path references across ${docs.length} docs all resolve.`,
  );
  process.exit(0);
}

console.error(
  `docs:check FAIL — ${misses.length} reference(s) point at files that do not exist:\n`,
);
for (const m of misses) {
  console.error(`  ${m.doc}:${m.line}  ->  \`${m.token}\`  (resolved: ${m.rel})`);
}
console.error(
  "\nFix the path, or — if the reference is intentional (future/aspirational, " +
    "gitignored, or historical) — add it to ALLOWLIST in scripts/check-doc-paths.cjs " +
    "or append `" +
    IGNORE_LINE_MARKER +
    "` to the line.",
);
process.exit(1);
